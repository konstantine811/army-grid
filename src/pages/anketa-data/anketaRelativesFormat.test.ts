import { describe, expect, it } from "vitest";
import { normalizeAnketaRelativesText } from "./anketaRelativesFormat";

describe("normalizeAnketaRelativesText", () => {
  it("rewrites a messy handwritten relatives block into canonical Ukrainian order", () => {
    expect(
      normalizeAnketaRelativesText(`Сімейний стан: Не одружений
Мати: мати померла 24-го о 2016 рік Зацепина Екатерина Лилівна Рядянська 87 кв 13
Батько: Нема не спілкується
Довірена особа: Зацепина Наталья Володиміровна, 097-387-34-80, м. Павлоград Советская 87 кв 13
Дитина: Нема`),
    ).toBe(`Сімейний стан: не одружений
Мати: Зацепіна Катерина Іллівна, померла у 2016 р., вул. Радянська, буд. 87, кв. 13
Батько: немає, не спілкується
Довірена особа: Зацепіна Наталія Володимирівна, м. Павлоград, вул. Радянська, буд. 87, кв. 13, тел: +380973873480
Дитина: немає`);
  });

  it("title-cases names and cities and collapses a duplicated trusted person", () => {
    expect(
      normalizeAnketaRelativesText(`Сімейний стан: цивільна дружина, жук анастасія петрівна, 1988 р.н., м. дніпро, бульвар європейський, буд. 2, кв. 43, тел: +380992928239
Мати: Косякіна Світлана Петрівна, м. Дніпро, 1957 р.н. пр. О. Поля буд. 10, 12 кв. 80, тел: +380972817301
Батько: Косякін Василь Олексійович, м. Дніпро, 1958 р.н. бульвар Європейський буд. 2, кв. 43, тел: +380675656940
Довірена особа: Жук Анастасія Петрівна, м. Дніпро, 1988 р.н. бульвар Європейський буд. 2, кв. 43, тел: +380992928239
Дитина: Песенко Анастасія Вадимівна, м. Дніпро, 2005 р.н. бульвар Європейський буд. 2, кв. 43, тел: +380687686078`),
    ).toBe(`Сімейний стан: цивільна дружина, Жук Анастасія Петрівна, 1988 р.н., м. Дніпро, бульвар Європейський, буд. 2, кв. 43, тел: +380992928239
Мати: Косякіна Світлана Петрівна, 1957 р.н., м. Дніпро, пр. О. Поля, буд. 10, 12 кв. 80, тел: +380972817301
Батько: Косякін Василь Олексійович, 1958 р.н., м. Дніпро, бульвар Європейський, буд. 2, кв. 43, тел: +380675656940
Довірена особа: цивільна дружина
Дитина: Песенко Анастасія Вадимівна, 2005 р.н., м. Дніпро, бульвар Європейський, буд. 2, кв. 43, тел: +380687686078`);
  });

  it("collapses a trusted person who is the mother to a role label", () => {
    expect(
      normalizeAnketaRelativesText(`Сімейний стан: не одружений
Мати: Іванова Марія Петрівна, м. Дніпро, тел: +380501112233
Батько: немає
Довірена особа: іванова марія петрівна, м. дніпро, тел: +380501112233
Дитина: немає`),
    ).toBe(`Сімейний стан: не одружений
Мати: Іванова Марія Петрівна, м. Дніпро, тел: +380501112233
Батько: немає
Довірена особа: мати
Дитина: немає`);
  });

  it("drops trailing немає, keeps birth before address, and collapses mother as trusted person", () => {
    expect(
      normalizeAnketaRelativesText(`Мати: Воробей Ірина Полікарпівна, 1955 р.н., м. Дніпро, вул. Б. Хмельницького буд. 25, кв. 36 немає
Батько: Помер
Довірена особа: Воробей Ірина Полікарпівна, м. Дніпро, 1955 р.н. вул. Б. Хмельницького буд. 25 А кв. 36 немає
Дитина: Судак Ангеліна Романівна, 16.06.2002 р.н. немає`),
    ).toBe(`Сімейний стан:
Мати: Воробей Ірина Полікарпівна, 1955 р.н., м. Дніпро, вул. Б. Хмельницького, буд. 25, кв. 36
Батько: помер
Довірена особа: мати
Дитина: Судак Ангеліна Романівна, 16.06.2002 р.н.`);
  });

  it("puts family status first and title-cases a lowercase spouse line", () => {
    expect(
      normalizeAnketaRelativesText(
        `Сімейний стан: зайцева світлана петрівна, 1978, цивільна дружина, м. дніпро, вул. тітова, буд. 15, кв. 26, тел: +380507037647`,
      ),
    ).toBe(
      `Сімейний стан: цивільна дружина, Зайцева Світлана Петрівна, 1978 р.н., м. Дніпро, вул. Тітова, буд. 15, кв. 26, тел: +380507037647
Мати:
Батько:
Довірена особа:
Дитина:`,
    );
  });
});
